function textW(str, sc) { return str.length * 6 * sc - sc; }

var FONT_STACK = "'DejaVu Sans Mono', ui-monospace, Menlo, Consolas, monospace";
function fontFor(sc) {
  // 7 rows of glyph + 1 row of descender room, snapped to whole pixels
  return Math.round(8 * sc) + "px " + FONT_STACK;
}

function text(ctx, str, x, y, sc, col, align) {
  str = String(str).toUpperCase();
  ctx.font = fontFor(sc);
  ctx.textBaseline = 'top';
  if (align === 'center') x -= Math.floor(textW(str, sc) / 2);
  else if (align === 'right') x -= textW(str, sc);
  x = Math.round(x); y = Math.round(y);
  ctx.fillStyle = col || PAT.ink;
  for (var c = 0; c < str.length; c++) {
    var g = GLYPHS[str.charAt(c)];
    if (!g) g = GLYPHS['?'];
    var ox = x + c * 6 * sc;
    for (var r = 0; r < 7; r++) {
      var bits = g[r];
      if (!bits) continue;
      // glyph rows are MSB-first: bit 4 is the LEFT pixel of the 5-wide cell
      var col0 = (bits >> 4) & 1, run = 1;
      for (var b = 1; b <= 5; b++) {
        var bit = (b < 5) ? ((bits >> (4 - b)) & 1) : 0;
        if (bit === col0) { run++; continue; }
        if (col0) ctx.fillRect(ox + (b - run) * sc, y + r * sc, run * sc, sc);
        col0 = bit; run = 1;
      }
    }
  }
}

function panel(ctx, x, y, w, h, fill, edge) {
  ctx.fillStyle = fill || 'rgba(4,23,11,0.66)';
  ctx.fillRect(x, y, w, h);
  if (edge !== false) {
    ctx.fillStyle = PAT.inkFaint;
    ctx.fillRect(x, y, w, 1); ctx.fillRect(x, y + h - 1, w, 1);
    ctx.fillRect(x, y, 1, h); ctx.fillRect(x + w - 1, y, 1, h);
  }
}
